/**
 * The sidebar is organized by audience (docs-strategy/03-piano-documentazione.md §2):
 * Get started (quickstart and the modules), Use Rational AI (users and builders), Administration & security,
 * Developers, Concepts, Reference (Settings screens), Help.
 *
 * Top-level sections are non-collapsible "flat labels"; the folders inside them
 * have NO `link`, so clicking a folder label only expands/collapses it
 * (Notion-style) and no `/category/...` index page is generated. The caret is
 * styled in src/css/sidebar.css.
 *
 * No files are moved and no doc URLs change: pages are referenced by id.
 * Every published page must appear here; `yarn build` fails otherwise only for
 * broken links, so check new pages are listed.
 */

type Items = SidebarsConfig[string];

const section = (label: string, items: Items) => ({
	type: "category" as const,
	label,
	collapsible: false,
	collapsed: false,
	items,
});

const folder = (label: string, ids: string[]) => ({
	type: "category" as const,
	label,
	collapsed: true,
	items: ids.map((id) => `operational-guides/${id}`),
});

